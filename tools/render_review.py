#!/usr/bin/env python3
"""Render each mock test's questions into crawlable HTML.

Search Console indexed the mock hub and the three 25-question tests after
we requested indexing, but refused all three full-length papers. The
reason is visible in the files: bihar-police-full-test-1.html is 43,326
characters, of which 35,454 - 82% - sit inside a <script> tag holding
window.KET_TEST. Strip the scripts and only 530 words of real text
remain, most of it header, nav and boilerplate. The hundred questions
and their explanations, which are the entire value of the page and are
original writing, are invisible in the served HTML.

Googlebot does execute JavaScript, but rendering is queued separately
and weighted less than what arrives in the initial response. For a site
with five external links that Google is already rationing crawl on, a
page that looks like 500 words of boilerplate is an easy "discovered,
not worth indexing" - which is exactly the verdict the three biggest
tests got, and exactly the ones with the worst script-to-text ratio.

So this writes the bank into the page as static HTML: every question,
its options, the correct answer and the explanation. That turns a
500-word page into a few thousand words of original Hindi, gives a
student a way to revise without sitting the test again, and costs
nothing at runtime because the quiz still reads window.KET_TEST.

The review block is collapsed behind <details> so it cannot spoil the
test for someone about to take it. Google indexes content inside
<details>; it is hidden from the eye, not from the crawler.

Generated from the same bank the quiz uses, so the two cannot disagree.
Run with --check to verify rather than write, which validate.py does.

Usage:
  python3 tools/render_review.py          # write the review blocks
  python3 tools/render_review.py --check  # exit 1 if any are stale
"""
import glob
import html
import json
import re
import sys

START = '<!-- review:start (generated by tools/render_review.py) -->'
END = '<!-- review:end -->'
LETTERS = ['A', 'B', 'C', 'D']


def bank(raw):
    """Pull the questions array out of window.KET_TEST."""
    m = re.search(r'window\.KET_TEST\s*=\s*\{(.*?)\};\s*</script>', raw, re.S)
    if not m:
        return None
    qm = re.search(r'questions:\s*(\[.*\])\s*$', m.group(1).strip(), re.S)
    if not qm:
        return None
    try:
        return json.loads(qm.group(1))
    except json.JSONDecodeError:
        return None


def block(questions, total_marks_note):
    """Build the static review section."""
    e = html.escape
    out = [START,
           '    <section id="review">',
           '      <h2>सभी प्रश्न, उत्तर और व्याख्या</h2>',
           '      <p>नीचे इस टेस्ट के सारे प्रश्न उत्तर और व्याख्या के साथ दिए गए हैं। '
           'यह उन लोगों के लिए है जो टेस्ट दे चुके हैं और दोहराना चाहते हैं, या जिन्हें '
           'सिर्फ पढ़कर तैयारी करनी है। <strong>अगर आप टेस्ट देने वाले हैं तो इसे अभी मत '
           'खोलिए</strong> — उत्तर पहले देख लेने पर अपनी असली तैयारी का पता नहीं चलेगा।</p>',
           '      <details class="review">',
           '        <summary>%d प्रश्न, उत्तर सहित खोलें</summary>' % len(questions)]
    for i, q in enumerate(questions, 1):
        topic = q.get('topic', '')
        out.append('        <div class="qrev">')
        out.append('          <h3>प्रश्न %d%s</h3>' % (
            i, ' <span class="topic">(%s)</span>' % e(topic) if topic else ''))
        out.append('          <p class="qtext">%s</p>' % e(q['q']))
        out.append('          <ol type="A">')
        for opt in q['options']:
            out.append('            <li>%s</li>' % e(str(opt)))
        out.append('          </ol>')
        ans = q.get('answer', 0)
        out.append('          <p class="ans"><strong>सही उत्तर:</strong> %s — %s</p>'
                   % (LETTERS[ans] if 0 <= ans < 4 else '?',
                      e(str(q['options'][ans]))))
        if q.get('explain'):
            out.append('          <p class="why">%s</p>' % e(q['explain']))
        out.append('        </div>')
    out.append('      </details>')
    out.append('      <p class="note">%s</p>' % total_marks_note)
    out.append('    </section>')
    out.append(END)
    return '\n'.join(out)


def main():
    check = '--check' in sys.argv
    stale, done, skipped = [], 0, []

    for f in sorted(glob.glob('mock/*.html')):
        raw = open(f, encoding='utf-8').read()
        qs = bank(raw)
        if not qs:
            skipped.append(f)
            continue
        note = ('ये सभी प्रश्न मूल रूप से लिखे गए हैं और किसी पुराने प्रश्नपत्र '
                'की नकल नहीं हैं। कोई त्रुटि दिखे तो '
                '<a href="../contact.html">हमें बताइए</a>।')
        new = block(qs, note)

        if START in raw and END in raw:
            cur = raw[raw.index(START):raw.index(END) + len(END)]
            if cur == new:
                continue
            if check:
                stale.append(f)
                continue
            raw = raw.replace(cur, new)
        else:
            if check:
                stale.append(f)
                continue
            # insert after the history container, before the explainer
            anchor = '<div id="historyWrap"></div>'
            if anchor not in raw:
                skipped.append(f + ' (no anchor)')
                continue
            raw = raw.replace(anchor, anchor + '\n\n' + new, 1)

        open(f, 'w', encoding='utf-8').write(raw)
        done += 1
        print('  %-44s %d questions rendered' % (f, len(qs)))

    if skipped:
        print('skipped (no question bank): %s' % ', '.join(skipped))
    if check:
        if stale:
            print('%d mock page(s) have a stale or missing review block:'
                  % len(stale))
            for f in stale:
                print('  %s' % f)
            print('\nrun: python3 tools/render_review.py')
            return 1
        print('every mock page has an up-to-date review block')
        return 0
    print('updated %d page(s)' % done if done else 'nothing to change')
    return 0


if __name__ == '__main__':
    sys.exit(main())
